/** Parses the mazefiles text format into east/south wall grids (row 0 = north). */
function parse(text) {
  const lines = text.split("\n")
  if (lines.length < 2 * N + 1) throw new Error("not 16x16")
  const eastWall = [], southWall = []
  let start = null
  const goals = []
  for (let r = 0; r < N; r++) {
    const cells = lines[2 * r + 1]
    const below = lines[2 * r + 2]
    if (cells.length < 4 * N + 1 || below.length < 4 * N + 1) throw new Error("not 16x16")
    eastWall.push([]), southWall.push([])
    for (let c = 0; c < N; c++) {
      eastWall[r].push(cells[4 * c + 4] === "|")
      southWall[r].push(below.slice(4 * c + 1, 4 * c + 4) === "---")
      const mark = cells[4 * c + 2]
      if (mark === "S") start = [c, r]
      if (mark === "G") goals.push([c, r])
    }
  }
  return { eastWall, southWall, start, goals }
}

const open = (m, [ax, ay], [bx, by]) =>
  ay === by ? !m.eastWall[ay][Math.min(ax, bx)] : !m.southWall[Math.min(ay, by)][ax]
const inside = ([x, y]) => x >= 0 && y >= 0 && x < N && y < N
const around = ([x, y]) => [[x, y - 1], [x + 1, y], [x, y + 1], [x - 1, y]].filter(inside)
const isGoal = ([x, y]) => (x === 7 || x === 8) && (y === 7 || y === 8)

/** Problems that would break the site's assumptions; empty when the maze is usable. */
function check(m) {
  const problems = []
  if (!m.start || m.start[0] !== 0 || m.start[1] !== N - 1) problems.push("start is not bottom-left")
  const goalOk = m.goals.length === 4 && m.goals.every(isGoal)
  if (!goalOk) problems.push("goal is not the centre 2x2")
  let entrances = 0
  for (const cell of [[7, 7], [8, 7], [7, 8], [8, 8]])
    for (const n of around(cell)) if (!isGoal(n) && open(m, cell, n)) entrances++
  if (entrances !== 1) problems.push(`${entrances} goal entrances`)
  const seen = new Set(["0,15"]), queue = [[0, N - 1]]
  for (let i = 0; i < queue.length; i++)
    for (const n of around(queue[i])) if (!seen.has(`${n}`) && open(m, queue[i], n)) seen.add(`${n}`), queue.push(n)
  if (![[7, 7], [8, 8]].some((g) => seen.has(`${g}`))) problems.push("goal unreachable")
  return problems
}

/** One hex digit per cell: 1 = east wall, 2 = south wall (other sides come from neighbours). */
function encode(m) {
  let out = ""
  for (let r = 0; r < N; r++)
    for (let c = 0; c < N; c++) out += ((m.eastWall[r][c] ? 1 : 0) | (m.southWall[r][c] ? 2 : 0)).toString(16)
  return out
}

const source = process.argv[2]
if (!source) throw new Error("usage: node scripts/import-mazes.mjs <mazefiles/classic>")

const entries = []
for (const [file, label] of Object.entries(SELECTION)) {
  const maze = parse(readFileSync(join(source, `${file}.txt`), "utf8"))
  const problems = check(maze)
  if (problems.length) {
    console.warn(`skip ${file}: ${problems.join(", ")}`)
    continue
  }
  entries.push(`  { id: ${JSON.stringify(file)}, label: ${JSON.stringify(label)}, walls: "${encode(maze)}" },`)
}

writeFileSync(
  "lib/maze-library.ts",
  `// Generated by scripts/import-mazes.mjs; do not edit by hand.
// Source: https://github.com/micromouseonline/mazefiles (classic). Mazes used in real competitions.
// Each walls string has one hex digit per cell, row by row from the north: 1 = east wall, 2 = south wall.

export const mazeLibrary = [
${entries.join("\n")}
]
`
)
console.log(`wrote ${entries.length} of ${Object.keys(SELECTION).length} mazes`)
